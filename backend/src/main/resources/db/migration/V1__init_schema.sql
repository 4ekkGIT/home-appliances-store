
CREATE TABLE categories (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    description TEXT,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE brands (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(100) NOT NULL UNIQUE,
    slug VARCHAR(120) NOT NULL UNIQUE,
    logo_url VARCHAR(500),
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE products (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id),
    brand_id BIGINT REFERENCES brands(id),
    name VARCHAR(200) NOT NULL,
    slug VARCHAR(220) NOT NULL UNIQUE,
    description TEXT,
    price NUMERIC(12, 2) NOT NULL CHECK (price >= 0),
    stock_quantity INTEGER NOT NULL DEFAULT 0
        CHECK (stock_quantity >= 0),
    image_url VARCHAR(500),
    is_active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE category_attributes (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_id BIGINT NOT NULL REFERENCES categories(id)
        ON DELETE CASCADE,
    name VARCHAR(100) NOT NULL,
    slug VARCHAR(120) NOT NULL,
    data_type VARCHAR(20) NOT NULL
        CHECK (data_type IN ('TEXT', 'NUMBER', 'BOOLEAN', 'SELECT')),
    unit VARCHAR(30),
    options JSONB NOT NULL DEFAULT '[]'::jsonb,
    is_required BOOLEAN NOT NULL DEFAULT FALSE,
    is_filterable BOOLEAN NOT NULL DEFAULT FALSE,
    display_order INTEGER NOT NULL DEFAULT 0,
    CONSTRAINT uq_category_attribute_slug
        UNIQUE (category_id, slug),
    CONSTRAINT uq_category_attribute_id_category
        UNIQUE (id, category_id)
);

CREATE TABLE product_attribute_values (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL REFERENCES products(id)
        ON DELETE CASCADE,
    attribute_id BIGINT NOT NULL REFERENCES category_attributes(id)
        ON DELETE CASCADE,
    value_text TEXT,
    value_number NUMERIC(14, 3),
    value_boolean BOOLEAN,
    CONSTRAINT uq_product_attribute
        UNIQUE (product_id, attribute_id),
    CONSTRAINT chk_single_attribute_value CHECK (
        num_nonnulls(value_text, value_number, value_boolean) = 1
        )
);

CREATE INDEX idx_products_category_id
    ON products(category_id);

CREATE INDEX idx_products_brand_id
    ON products(brand_id);

CREATE INDEX idx_products_is_active
    ON products(is_active);

CREATE INDEX idx_products_name
    ON products(name);

CREATE INDEX idx_category_attributes_category_id
    ON category_attributes(category_id);

CREATE INDEX idx_product_attribute_values_attribute_number
    ON product_attribute_values(attribute_id, value_number);

CREATE INDEX idx_product_attribute_values_attribute_text
    ON product_attribute_values(attribute_id, value_text);
