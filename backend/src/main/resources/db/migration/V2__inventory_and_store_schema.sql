CREATE UNIQUE INDEX uq_user_default_address
    ON user_addresses(user_id)
    WHERE is_default = TRUE;


-- =============================================
-- 6. PRODUCT UNITS
-- =============================================

CREATE TABLE product_units (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id BIGINT NOT NULL
        REFERENCES products(id),
    warehouse_id BIGINT
        REFERENCES warehouses(id),
    inventory_code VARCHAR(100) NOT NULL UNIQUE,
    serial_number VARCHAR(150),
    status VARCHAR(20) NOT NULL DEFAULT 'AVAILABLE'
        CHECK (
            status IN (
                        'AVAILABLE',
                        'RESERVED',
                        'SOLD',
                        'DAMAGED',
                        'RETURNED',
                        'WRITTEN_OFF'
                )
            ),
    received_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_product_unit_id_product
        UNIQUE (id, product_id),

    CONSTRAINT chk_product_unit_location
        CHECK (
            (
                status IN (
                            'AVAILABLE',
                            'RESERVED',
                            'DAMAGED',
                            'RETURNED'
                    )
                    AND warehouse_id IS NOT NULL
                )
                OR
            (
                status IN ('SOLD', 'WRITTEN_OFF')
                                               AND warehouse_id IS NULL
                )
            )
);

CREATE UNIQUE INDEX uq_product_unit_serial
    ON product_units(serial_number)
    WHERE serial_number IS NOT NULL;

CREATE INDEX idx_product_units_product_status
    ON product_units(product_id, status);

CREATE INDEX idx_product_units_warehouse_status
    ON product_units(warehouse_id, status);


-- =============================================
-- 7. ORDERS
-- =============================================

CREATE TABLE orders (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id BIGINT NOT NULL
        REFERENCES users(id),
    status VARCHAR(20) NOT NULL DEFAULT 'PENDING'
        CHECK (
            status IN (
                        'PENDING',
                        'CONFIRMED',
                        'PROCESSING',
                        'SHIPPED',
                        'DELIVERED',
                        'CANCELLED'
                )
            ),
    total_amount NUMERIC(12, 2) NOT NULL DEFAULT 0
        CHECK (total_amount >= 0),
    shipping_address JSONB NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX idx_orders_user_created
    ON orders(user_id, created_at DESC);

CREATE INDEX idx_orders_status
    ON orders(status);


-- =============================================
-- 8. ORDER ITEMS
-- =============================================

CREATE TABLE order_items (
                             id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                             order_id BIGINT NOT NULL
                                 REFERENCES orders(id),
                             product_id BIGINT NOT NULL
                                 REFERENCES products(id),
                             product_name VARCHAR(200) NOT NULL,
                             quantity INTEGER NOT NULL
                                 CHECK (quantity > 0),
                             unit_price NUMERIC(12, 2) NOT NULL
                                 CHECK (unit_price >= 0),

                             line_total NUMERIC(14, 2)
                                 GENERATED ALWAYS AS (quantity * unit_price) STORED,

                             CONSTRAINT uq_order_item_id_product
                                 UNIQUE (id, product_id)
);


-- =============================================
-- 9. INVENTORY MOVEMENTS
-- =============================================

CREATE TABLE inventory_movements (
                                     id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                     product_unit_id BIGINT NOT NULL
                                         REFERENCES product_units(id),
                                     from_warehouse_id BIGINT
                                         REFERENCES warehouses(id),
                                     to_warehouse_id BIGINT
                                         REFERENCES warehouses(id),
                                     order_id BIGINT
                                         REFERENCES orders(id),
                                     actor_user_id BIGINT
                                         REFERENCES users(id),

                                     movement_type VARCHAR(20) NOT NULL
                                         CHECK (
                                             movement_type IN (
                                                               'RECEIPT',
                                                               'TRANSFER',
                                                               'RESERVATION',
                                                               'RELEASE',
                                                               'SALE',
                                                               'RETURN',
                                                               'WRITE_OFF',
                                                               'STATUS_CHANGE'
                                                 )
                                             ),

                                     previous_status VARCHAR(20)
                                         CHECK (
                                             previous_status IS NULL OR previous_status IN (
                                                                                            'AVAILABLE',
                                                                                            'RESERVED',
                                                                                            'SOLD',
                                                                                            'DAMAGED',
                                                                                            'RETURNED',
                                                                                            'WRITTEN_OFF'
                                                 )
                                             ),

                                     new_status VARCHAR(20)
                                         CHECK (
                                             new_status IS NULL OR new_status IN (
                                                                                  'AVAILABLE',
                                                                                  'RESERVED',
                                                                                  'SOLD',
                                                                                  'DAMAGED',
                                                                                  'RETURNED',
                                                                                  'WRITTEN_OFF'
                                                 )
                                             ),

                                     comment TEXT,
                                     created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,

                                     CONSTRAINT chk_inventory_movement_status
                                         CHECK (
                                             previous_status IS NOT NULL
                                                 OR new_status IS NOT NULL
                                             ),

                                     CONSTRAINT chk_inventory_transfer
                                         CHECK (
                                             movement_type <> 'TRANSFER'
                                                 OR (
                                                 from_warehouse_id IS NOT NULL
                                                     AND to_warehouse_id IS NOT NULL
                                                     AND from_warehouse_id <> to_warehouse_id
                                                 )
                                             )
);

CREATE INDEX idx_inventory_movements_unit
    ON inventory_movements(product_unit_id, created_at DESC);

CREATE INDEX idx_inventory_movements_order
    ON inventory_movements(order_id);


