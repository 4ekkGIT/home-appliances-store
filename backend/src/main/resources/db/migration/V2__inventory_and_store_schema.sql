-- =============================================
-- 12. ORDER ITEM UNITS
-- =============================================

CREATE TABLE order_item_units (
                                  id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                                  order_item_id BIGINT NOT NULL,
                                  product_unit_id BIGINT NOT NULL,
                                  product_id BIGINT NOT NULL,
                                  reserved_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
                                  released_at TIMESTAMPTZ,

                                  CONSTRAINT fk_oiu_order_item_product
                                      FOREIGN KEY (order_item_id, product_id)
                                          REFERENCES order_items(id, product_id),

                                  CONSTRAINT fk_oiu_product_unit_product
                                      FOREIGN KEY (product_unit_id, product_id)
                                          REFERENCES product_units(id, product_id),

                                  CONSTRAINT chk_order_unit_release
                                      CHECK (
                                          released_at IS NULL
                                              OR released_at >= reserved_at
                                          )
);

-- A physical unit can have only one active reservation.
CREATE UNIQUE INDEX uq_active_product_unit_reservation
    ON order_item_units(product_unit_id)
    WHERE released_at IS NULL;

CREATE UNIQUE INDEX uq_active_order_item_unit
    ON order_item_units(order_item_id, product_unit_id)
    WHERE released_at IS NULL;


