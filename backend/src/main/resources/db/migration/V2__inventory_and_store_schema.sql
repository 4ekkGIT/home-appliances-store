-- 13. MIGRATE EXISTING STOCK
-- =============================================

INSERT INTO product_units (
    product_id,
    warehouse_id,
    inventory_code,
    status,
    received_at
)
SELECT
    p.id,
    w.id,
    'LEGACY-' || p.id || '-' || gs.unit_number,
    'AVAILABLE',
    p.created_at
FROM products p
         CROSS JOIN warehouses w
         CROSS JOIN LATERAL
    generate_series(1, p.stock_quantity) AS gs(unit_number)
WHERE w.name = 'Main Warehouse';


